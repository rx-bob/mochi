Mochi::Test.test("descendant clicks keep target data separate from handler identity and recover after oversized data") do
  mount "probe-root"
  click "span"
  assert_text ".selected", ""
  assert_text ".target", ""
  assert_text ".part", "label"
  assert_text ".current", "log-001"
  assert_text ".calls", "1"
  click ".oversize-target"
  expect_error "ABI event argument bytes exhausted"
  click "span"
  assert_text ".calls", "1"
  click ".reset"
  click "span"
  assert_text ".calls", "2"
  click ".oversize-handler"
  expect_error "ABI event argument bytes exhausted"
  click "span"
  assert_text ".calls", "2"
  click ".reset"
  click "span"
  assert_text ".calls", "3"
  assert_text ".current", "log-001"
end
