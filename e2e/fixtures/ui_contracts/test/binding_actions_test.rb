Mochi::Test.test("bindings precede handlers in either attribute order") do
  mount "binding-actions-root"
  fill ".first", "first"
  assert_text ".seen", "first:first"
  assert_text ".calls", "1"
  fill ".last", "last"
  assert_text ".seen", "last:last"
  assert_text ".calls", "2"
  click ".check-first"
  assert_text ".seen", "checked"
  click ".check-last"
  assert_text ".seen", "unchecked"
  assert_text ".calls", "4"
  fill ".select-first", "b"
  assert_text ".seen", "b:b"
  assert_text ".calls", "5"
  fill ".select-last", "a"
  assert_text ".seen", "a:a"
  assert_text ".calls", "6"
end

Mochi::Test.test("bound row handlers retain scope after moves and branch recreation") do
  mount "binding-actions-root"
  fill "[data-id='a'] .row-draft", "before"
  assert_text ".seen", "a:0:before:before"
  click ".reorder"
  fill "[data-id='a'] .row-draft", "after"
  assert_text ".seen", "a:1:after:after"
  click "[data-id='a'] .row-check"
  assert_text ".seen", "checked"
  fill "[data-id='a'] .row-select", "b"
  assert_text ".seen", "b:b"
  click ".reset"
  assert_value "[data-id='a'] .row-draft", "reset"
  assert_value "[data-id='a'] .row-select", "a"
  click "[data-id='a'] .row-check"
  assert_text ".seen", "checked"
  assert_text ".calls", "5"
  3.times do |index|
    click ".toggle"
    click ".toggle"
    fill ".branch", "branch-#{index}"
    assert_text ".seen", "branch-#{index}:branch-#{index}"
    assert_text ".calls", (index + 6).to_s
  end
  remount "binding-actions-root"
  fill ".first", "remount"
  assert_text ".seen", "remount:remount"
  assert_text ".calls", "1"
end
