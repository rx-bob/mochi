Mochi::Test.test("select a station, reorder the rows, and inspect its details") do
  mount "record-inspector"
  assert_text "[data-view='selection']", "Selected station 01"
  wait_for "[data-station='02'] >>> [data-id='02']"
  focus "[data-station='02'] >>> [data-id='02']"
  checkpoint "initial"
  click "[data-station='02'] >>> [data-id='02']"
  assert_text "[data-view='selection']", "Selected station 02"
  assert_attribute "[data-station='02'] >>> [data-id='02']", "aria-pressed", "true"
  focus "[data-station='02'] >>> [data-id='02']"
  checkpoint "selected"
  focus "[data-action='reverse']"
  press "Enter"
  assert_attribute "station-row >>> [data-id]", "data-id", "03"
  assert_text "[data-view='selection']", "Selected station 02"
  focus "[data-action='details']"
  press "Space"
  assert_focused "[data-action='details']"
  wait_for "station-details >>> [data-view='details']"
  assert_text "station-details >>> [data-view='details']", "Showing details for station 02"
  checkpoint "reversed"
  remount
  assert_text "[data-view='selection']", "Selected station 01"
  wait_for "[data-station='01'] >>> [data-id='01']"
  assert_attribute "[data-station='01'] >>> [data-id='01']", "aria-pressed", "true"
end
